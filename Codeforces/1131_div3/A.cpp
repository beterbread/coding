typedef unsigned long long ull;
#define all(x) (x).begin(), (x).end()
#define rall(x) (x).rbegin(), (x).rend()
#define pb push_backD
#define ff first
#define ss second
#define each(x, a) for (auto &x : a)                    
#define FOR(i, n) for (int i = 0; i < (n); ++i)           
#define FORD(i, n) for (int i = (n) - 1; i >= 0; --i)   

void solve() {
    int n,m; cin >> n >> m;
    string p,q; cin >> p >> q;
    int cnt = 0;
    FOR(i,m) {
        if (p.find(q[i]) != string::npos) {
            p.erase(p.find(q[i]),1);
            cnt++;
        }
    }
    sort(all(p));
    cout << (p == "isx" && cnt == m ? "YES" : "NO") << '\n';
}

int main() 
{ 
    cin.tie(0)->sync_with_stdio(0);
    int t; cin >> t;
    while (t--) solve();
    return 0; 
} 
